// FODMAP-ainesosatietokanta.
//
// Koottu julkaistun FODMAP-tutkimuksen pohjalta (Monash University, King's
// College London ym. julkaisut). EI kliinisesti tarkistettu – arviot ovat
// suuntaa-antavia ja tarkoituksella varovaisia. Muokkaa vapaasti omien
// kokemusten mukaan: jokainen rivi on yksi ainesosa.
//
// Hakusanat (patterns) ovat pienillä kirjaimilla kirjoitettuja merkkijonoja,
// joita etsitään ainesosan tekstistä osana sanaa. Suomen yhdyssanat toimivat
// siis suoraan: "sipuli" löytyy myös sanoista "sipulijauhe" ja "valkosipuli".
// Jos useampi hakusana osuu samaan kohtaan, pisin voittaa – siksi
// "vehnätärkkelys" (vähä-FODMAP) ohittaa "vehnä"-osuman (runsas-FODMAP).
// Mukana on myös ruotsin- ja englanninkielisiä hakusanoja niitä tuotteita
// varten, joista suomenkielinen luettelo puuttuu.
//
// Lyhyille hakusanoille voi antaa etuliitteen:
//   "^oat"  – osuma vain sanan alussa (ei "goat")
//   "=voi"  – vain kokonainen sana (ei "voileipä")

export type FodmapGroup = 'fruktaanit' | 'gos' | 'laktoosi' | 'fruktoosi' | 'polyolit';

export type Level = 'low' | 'moderate' | 'high' | 'unknown';

export interface IngredientEntry {
  id: string;
  /** Näytettävä nimi. */
  name: string;
  level: Level;
  groups: FodmapGroup[];
  patterns: string[];
  /** Haitallinen pieninäkin määrinä (esim. valkosipuli, inuliini, sorbitoli). */
  potent?: boolean;
  /** Ohita sulkeissa luetellut ala-ainesosat (esim. "glukoosisiirappi (vehnä)"). */
  absorbsChildren?: boolean;
  note?: string;
  /**
   * Muu kuin FODMAP-syy, miksi aine voi pahentaa IBS-oireita (kofeiini, hiilihappo, tulinen, alkoholi,
   * eräät emulgointiaineet). Ei vaikuta FODMAP-arvioon; näytetään erikseen.
   */
  trigger?: string;
}

